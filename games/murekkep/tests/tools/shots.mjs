/* global window */
// Scratch screenshot driver (not part of the gate). Usage: node tests/shots.mjs <port> <outdir>
import { chromium } from '@playwright/test';
const [port, out] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push(e.message));
const st = () => page.evaluate(() => window.__OYUN__.state());
const act = (n, p) => page.evaluate(([n, p]) => window.__OYUN__.act(n, p), [n, p]);
const scene = (k) => page.waitForFunction((k) => window.__OYUN__?.state().scene === k, k, { timeout: 15000 });
await page.goto(`http://127.0.0.1:${port}/?test=1&seed=1&lang=en`);
await page.waitForFunction(() => window.__OYUN__?.ready === true);
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/menu.png` });
await act('play'); await scene('maps'); await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/maps.png` });
await act('sheet', { index: 0 }); await scene('game'); await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/game-start.png` });
await act('auto-play', { ticks: 99999 });
await page.waitForTimeout(9000);
await page.screenshot({ path: `${out}/game-early.png` });
console.log(JSON.stringify((await st()).data).slice(0, 400));
await act('fast-forward', 250); await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/game-mid.png` });
console.log(JSON.stringify((await st()).data).slice(0, 300));
await act('fast-forward', 300); await page.waitForTimeout(800);
const s = await st();
if (s.scene === 'game') await page.screenshot({ path: `${out}/game-late.png` });
await scene('result').catch(() => act('fast-forward', 3000));
await scene('result'); await page.waitForTimeout(1600);
await page.screenshot({ path: `${out}/result.png` });
console.log(JSON.stringify((await st()).data));
console.log('errors', JSON.stringify(errors));
await browser.close();
